//! An extract of cldr-json 49.0.0 for `ru` and `en` (design section 13.9, `tests/data.rs`).
//!
//! The values were copied by a script kept outside the repository from the `cldr-misc-full`
//! (`delimiters`), `cldr-numbers-full` (`numbers`), `cldr-dates-full` (`ca-gregorian`) and
//! `cldr-units-full` (`units`) files of cldr-json 49.0.0, read on 2026-11-21 (design section
//! 14.8). `en-US` has no file of its own and inherits `en` (section 7.3), so the `en` values stand
//! for it. A unit is listed by its CLDR id with the `unitPattern-count-other` string of its
//! short (and, for three English units, narrow) form; a CLDR update is a visible change here.
//! The module is declared by `tests/data.rs` with `#[path]`.

#![allow(dead_code)]

/// The CLDR values of one locale.
pub struct Locale {
    /// `quotationStart`, `quotationEnd`, `alternateQuotationStart`, `alternateQuotationEnd`.
    pub delimiters: [&'static str; 4],
    /// The `symbols-numberSystem-latn` entry `decimal`.
    pub decimal: &'static str,
    /// The entry `group`.
    pub group: &'static str,
    /// `minimumGroupingDigits`.
    pub minimum_grouping_digits: u8,
    /// The entry `minusSign` (typolish deviates, section 7.5).
    pub minus_sign: &'static str,
    /// `percentFormats-numberSystem-latn` `standard`.
    pub percent_pattern: &'static str,
    /// `miscPatterns-numberSystem-latn` `range`.
    pub range_pattern: &'static str,
    /// The entry `nan`.
    pub nan: &'static str,
    /// The entry `infinity`.
    pub infinity: &'static str,
    /// Gregorian format wide month names, January first.
    pub months_wide: [&'static str; 12],
    /// Gregorian format abbreviated month names, January first.
    pub months_abbreviated: [&'static str; 12],
    /// Short unit patterns of the units that the design marks "CLDR 49": `(id, pattern)`.
    pub units_short: &'static [(&'static str, &'static str)],
    /// Narrow unit patterns of the units that the design marks "CLDR 49".
    pub units_narrow: &'static [(&'static str, &'static str)],
}

